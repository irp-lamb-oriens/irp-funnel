<script lang="ts">
  /**
   * CardFieldsAccordion.svelte
   * ────────────────────────────────────────────────────────────────────────
   *
   * Renders EVERY top-level key from `client.rawDoc` (the verbatim Firestore
   * document) as a collapsible group. Each group's value is delegated to
   * <FieldValueViewer>, which knows how to pretty-print primitives, arrays,
   * nested objects, transcripts, dates, links, emails, phone numbers, …
   *
   * Why a "grouped" layout (and not just a flat list)
   * ─────────────────────────────────────────────────
   * The old version dumped every value through <EditableField>, which
   * fell back to JSON.stringify for arrays/objects — operators saw walls of
   * raw JSON. Now:
   *   - Primitives (string/number/bool) sit in a "Primary" group at the top,
   *     edited inline via <FieldValueViewer> → <EditableField>.
   *   - Arrays each get their own collapsed group with an item count.
   *   - Objects each get their own collapsed group, recursing into the same
   *     viewer so deeply-nested calendar events / consultations / extracted
   *     fields all render beautifully without truncation.
   *
   * Read-only paths are pre-flagged so primitive descendants render as
   * static text (no pencil) for fields whose source-of-truth is not the
   * operator (activityLog, transcriptInsights, lastCalendarEvent.notes.text,
   * pipelineStage, etc.).
   *
   * Used inline on every kanban card AND inside the detail panel's "Overview
   * → Advanced fields" disclosure.
   */

  import FieldValueViewer from './FieldValueViewer.svelte';
  import { humanizeFieldLabel } from '../store.ts';

  export let clientId: string;
  export let rawDoc: Record<string, any> | undefined;

  /** Whole subtrees the schema-agnostic editor refuses (top-level keys). */
  const READONLY: ReadonlySet<string> = new Set([
    'activityLog',
    'createdAt',
    'sessionId',
    'pipelineStage',
    'transcriptInsights', // generated by the LLM, not by the operator
    'lastCalendarEvent',  // sourced from Google Calendar + Gemini
    'consultations',      // per-element editing happens via the Overview tab
    'notes',              // notes have a dedicated endpoint
  ]);

  /** Hide entirely — purely internal bookkeeping no operator should care about. */
  const HIDDEN: ReadonlySet<string> = new Set([
    'currentEmailQueueAttempt',
    'lastChatbotInteraction',
    'lastBookConsultationContext',
  ]);

  // ── friendly icons + tones for top-level keys (operators recognise these) ─
  function iconFor(key: string): string {
    if (/email/i.test(key)) return '✉️';
    if (/phone|whatsapp/i.test(key)) return '📞';
    if (/transcript/i.test(key)) return '📝';
    if (/calendar|event|meeting/i.test(key)) return '📅';
    if (/consultation/i.test(key)) return '💬';
    if (/insights/i.test(key)) return '🧠';
    if (/activity|log/i.test(key)) return '🛣';
    if (/stage|pipeline/i.test(key)) return '🚦';
    if (/notes/i.test(key)) return '🗒';
    if (/origin|destination|route|address/i.test(key)) return '🌍';
    if (/budget|price|amount|cost/i.test(key)) return '💰';
    if (/vehicle|car/i.test(key)) return '🚗';
    if (/property|home|house/i.test(key)) return '🏠';
    if (/created|At$/i.test(key)) return '🕒';
    if (/drip|enabled|active/i.test(key)) return '⚡';
    return '·';
  }

  /** Counts so the group header can show "(3 items)" without expanding. */
  function summaryFor(value: unknown): string {
    if (value === null || value === undefined) return '—';
    if (typeof value === 'string') {
      if (value.length === 0) return 'empty';
      if (value.length > 80) return `${value.length.toLocaleString()} chars`;
      return value;
    }
    if (typeof value === 'number' || typeof value === 'boolean') return String(value);
    if (Array.isArray(value)) return `${value.length} item${value.length === 1 ? '' : 's'}`;
    if (typeof value === 'object') return `${Object.keys(value as object).length} field${Object.keys(value as object).length === 1 ? '' : 's'}`;
    return typeof value;
  }

  function isComplex(v: unknown): boolean {
    return v !== null && typeof v === 'object'; // arrays + objects
  }

  $: entries = Object.entries(rawDoc || {})
    .filter(([k]) => !HIDDEN.has(k))
    .sort(([ka, va], [kb, vb]) => {
      // Primitives first, then arrays, then objects. Inside each group → A→Z.
      const score = (v: unknown) =>
        v === null || ['string', 'number', 'boolean'].includes(typeof v) ? 0 : Array.isArray(v) ? 1 : 2;
      return score(va) - score(vb) || ka.localeCompare(kb);
    });

  // Track which groups are open. Default: primitives auto-open (low effort to
  // skim), complex shapes start collapsed (avoid wall-of-JSON on first paint).
  const open: Record<string, boolean> = {};
  $: entries.forEach(([k, v]) => {
    if (open[k] === undefined) open[k] = !isComplex(v);
  });

  function toggle(k: string) {
    open[k] = !open[k];
    // Force Svelte reactivity on the index-signature object.
    // eslint-disable-next-line no-self-assign
    open;
  }
</script>

<div class="fields-accordion-v2">
  {#if entries.length === 0}
    <p class="fields-accordion-v2__empty">No document fields available.</p>
  {:else}
    {#each entries as [key, value] (key)}
      {@const complex = isComplex(value)}
      <section
        class="fields-accordion-v2__group"
        class:fields-accordion-v2__group--complex={complex}
        class:fields-accordion-v2__group--open={open[key]}
      >
        <button
          type="button"
          class="fields-accordion-v2__group-header"
          on:click={() => toggle(key)}
          aria-expanded={open[key]}
        >
          <span class="fields-accordion-v2__group-icon" aria-hidden="true">{iconFor(key)}</span>
          <span class="fields-accordion-v2__group-label">{humanizeFieldLabel(key)}</span>
          <span class="fields-accordion-v2__group-summary">{summaryFor(value)}</span>
          {#if complex}
            <span class="fields-accordion-v2__group-chevron" aria-hidden="true">▾</span>
          {/if}
        </button>

        {#if open[key]}
          <div class="fields-accordion-v2__group-body">
            <FieldValueViewer
              {clientId}
              path={key}
              {value}
              readonly={READONLY.has(key)}
              depth={0}
            />
          </div>
        {/if}
      </section>
    {/each}
  {/if}
</div>
